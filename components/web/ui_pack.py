"""Pack the web UI files into a C source file (build step of components/web).

Usage: ui_pack.py <ui directory> <output .c file>

Every regular file directly in the UI directory becomes one entry of the
`web_ui_assets` table (priv_include/web_assets.h), served at "/<file name>";
"index.html" is also served at "/". Files are gzip-compressed here (fixed
timestamp, so the output only changes with the content); a file that already
ends in ".gz" is embedded as it is under the name without ".gz". Skipped:
dot files and Markdown (*.md) notes. Names must match [A-Za-z0-9._-]+ and
"index.html" must exist.
"""

import gzip
import os
import re
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".webmanifest": "application/manifest+json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".woff2": "font/woff2",
    ".txt": "text/plain; charset=utf-8",
}

NAME_RE = re.compile(r"^[A-Za-z0-9._-]+$")


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return "\n".join(lines) if lines else "    0x00,"


def main():
    if len(sys.argv) != 3:
        sys.stderr.write(__doc__)
        return 2
    ui_dir, out_path = sys.argv[1], sys.argv[2]
    entries = []
    for name in sorted(os.listdir(ui_dir)):
        path = os.path.join(ui_dir, name)
        if not os.path.isfile(path) or name.startswith(".") or name.lower().endswith(".md"):
            continue
        served = name[:-3] if name.endswith(".gz") else name
        if not NAME_RE.match(served):
            sys.stderr.write("ui_pack: file name not allowed: %s\n" % name)
            return 1
        ext = os.path.splitext(served)[1].lower()
        if ext not in MIME:
            sys.stderr.write("ui_pack: unknown file type (add it to MIME): %s\n" % name)
            return 1
        with open(path, "rb") as f:
            raw = f.read()
        data = raw if name.endswith(".gz") else gzip.compress(raw, compresslevel=9, mtime=0)
        entries.append((served, MIME[ext], data))
    names = [e[0] for e in entries]
    if "index.html" not in names:
        sys.stderr.write("ui_pack: %s has no index.html\n" % ui_dir)
        return 1
    if len(set(names)) != len(names):
        sys.stderr.write("ui_pack: a file exists both plain and as .gz\n")
        return 1

    out = []
    out.append("/* Generated by ui_pack.py from components/web/ui: do not edit. */")
    out.append('#include "web_assets.h"')
    out.append("")
    for i, (served, _, data) in enumerate(entries):
        out.append("/* /%s: %d bytes gzipped */" % (served, len(data)))
        out.append("static const uint8_t s_asset_%d[%d] = {" % (i, max(len(data), 1)))
        out.append(c_bytes(data))
        out.append("};")
        out.append("")
    out.append("const web_asset_t web_ui_assets[] = {")
    for i, (served, mime, data) in enumerate(entries):
        out.append('    { "/%s", "%s", s_asset_%d, %du },' % (served, mime, i, len(data)))
    out.append("};")
    out.append("")
    out.append("const size_t web_ui_asset_count = sizeof(web_ui_assets) / sizeof(web_ui_assets[0]);")
    out.append("")
    text = "\n".join(out)
    with open(out_path, "w", encoding="ascii") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
