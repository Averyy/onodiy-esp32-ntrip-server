size_t rtcm_make_frame(uint8_t *out, const uint8_t *payload, size_t n)
{
    out[0] = GNSS_RTCM3_PREAMBLE;
    out[1] = (uint8_t)((n >> 8) & 0x03u);
    out[2] = (uint8_t)(n & 0xFFu);
    memcpy(out + 3, payload, n);
    uint32_t crc = gnss_rtcm3_crc24q(out, n + 3);
    out[n + 3] = (uint8_t)(crc >> 16);
    out[n + 4] = (uint8_t)(crc >> 8);
    out[n + 5] = (uint8_t)crc;
    return n + 6;
}
